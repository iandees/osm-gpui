//! iD tagging schema preset support: vendored preset/area-key data,
//! geometry classification, and geometry-aware tag matching. Read-only
//! (no editing UI) — mirrors the shape of `nsi.rs` but with vendored
//! rather than runtime-fetched data. See
//! `docs/superpowers/specs/2026-07-07-id-preset-labels-design.md`.

use crate::osm::OsmData;
use crate::preset_translations::{active, PresetTranslations};
use crate::selection::FeatureKind;
use std::collections::HashMap;
use std::sync::OnceLock;

const PRESETS_JSON: &str = include_str!("../assets/presets/presets.json");
const AREA_KEYS_JSON: &str = include_str!("../assets/presets/area_keys.json");

// `PRESET_ICONS`: every `assets/presets/icons/*.svg` embedded in the binary,
// sorted by icon name (generated by `build.rs`).
include!(concat!(env!("OUT_DIR"), "/preset_icons.rs"));

/// Prefix of the asset paths the preset icons are served under (see
/// `crate::assets::AppAssets`).
pub const ICON_ASSET_DIR: &str = "preset-icons/";

static PRESET_INDEX: OnceLock<PresetIndex> = OnceLock::new();
static AREA_KEYS: OnceLock<AreaKeys> = OnceLock::new();

/// The vendored preset index, parsed once on first access.
pub fn preset_index() -> &'static PresetIndex {
    PRESET_INDEX.get_or_init(|| {
        PresetIndex::from_json(PRESETS_JSON)
            .expect("vendored assets/presets/presets.json must parse")
    })
}

/// The vendored area-key table, parsed once on first access.
pub fn area_keys() -> &'static AreaKeys {
    AREA_KEYS.get_or_init(|| {
        AreaKeys::from_json(AREA_KEYS_JSON)
            .expect("vendored assets/presets/area_keys.json must parse")
    })
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Geometry {
    Point,
    Vertex,
    Line,
    Area,
    Relation,
}

impl Geometry {
    /// Name used when no preset matches at all (should be rare in
    /// practice, since the vendored schema itself includes a
    /// geometry-only fallback preset per `Geometry` variant).
    pub fn fallback_name(&self) -> gpui::SharedString {
        match self {
            Geometry::Point => crate::tr!("geometry.point"),
            Geometry::Vertex => crate::tr!("geometry.vertex"),
            Geometry::Line => crate::tr!("geometry.line"),
            Geometry::Area => crate::tr!("geometry.area"),
            Geometry::Relation => crate::tr!("geometry.relation"),
        }
    }
}

fn default_match_score() -> f32 {
    1.0
}

#[derive(Debug, Clone, serde::Deserialize)]
pub struct Preset {
    pub id: String,
    pub name: String,
    #[serde(default)]
    pub icon: Option<String>,
    #[serde(default)]
    pub tags: HashMap<String, String>,
    pub geometry: Vec<Geometry>,
    #[serde(default = "default_match_score")]
    pub match_score: f32,
    #[serde(default)]
    pub fields: Vec<String>,
    #[serde(default)]
    pub more_fields: Vec<String>,
}

impl Preset {
    /// The name to show: its translation when `translations` has one, else
    /// the English schema name. Borrows, so it costs nothing per frame.
    pub fn display_name<'a>(&'a self, translations: Option<&'a PresetTranslations>) -> &'a str {
        translations
            .and_then(|t| t.preset_name(&self.id))
            .unwrap_or(&self.name)
    }
}

/// A parsed, in-memory collection of vendored `Preset`s.
pub struct PresetIndex {
    presets: Vec<Preset>,
}

impl PresetIndex {
    /// Parse a JSON array of `Preset` (the vendored `assets/presets/presets.json`
    /// shape, or a small fixture array in tests).
    pub fn from_json(body: &str) -> Result<Self, serde_json::Error> {
        let presets: Vec<Preset> = serde_json::from_str(body)?;
        Ok(Self { presets })
    }

    pub fn len(&self) -> usize {
        self.presets.len()
    }

    pub fn is_empty(&self) -> bool {
        self.presets.is_empty()
    }

    /// Every preset in the index.
    pub fn iter(&self) -> impl Iterator<Item = &Preset> {
        self.presets.iter()
    }

    /// Find the best-matching preset for a feature's tags and geometry.
    /// A preset matches only if every one of its required `tags` entries
    /// is present on the feature (`"*"` means "key present, any value")
    /// and its `geometry` list includes the feature's geometry. Among
    /// matches, the preset with the most matched tag pairs wins; ties are
    /// broken by `match_score` descending.
    pub fn match_feature(
        &self,
        tags: &HashMap<String, String>,
        geometry: Geometry,
    ) -> Option<&Preset> {
        self.presets
            .iter()
            .filter(|p| p.geometry.contains(&geometry))
            .filter_map(|p| {
                let mut matched = 0usize;
                for (key, value) in &p.tags {
                    match tags.get(key) {
                        Some(actual) if value == "*" || actual == value => matched += 1,
                        _ => return None,
                    }
                }
                Some((matched, p))
            })
            .max_by(|(matched_a, preset_a), (matched_b, preset_b)| {
                matched_a.cmp(matched_b).then(
                    preset_a
                        .match_score
                        .partial_cmp(&preset_b.match_score)
                        .unwrap_or(std::cmp::Ordering::Equal),
                )
            })
            .map(|(_, p)| p)
    }

    /// Look up a preset by its exact `id` (e.g. `"amenity/cafe"`).
    pub fn get(&self, id: &str) -> Option<&Preset> {
        self.presets.iter().find(|p| p.id == id)
    }

    /// Search presets by name (case-insensitive substring, same normalize
    /// approach as brand search elsewhere in this codebase), filtered to
    /// only presets whose `geometry` includes `geometry`. Capped at
    /// `limit` results, unordered beyond "substring matches first". Uses
    /// the active UI language's translations (see [`Self::search_in`]).
    pub fn search(&self, query: &str, geometry: Geometry, limit: usize) -> Vec<&Preset> {
        self.search_in(active(), query, geometry, limit)
    }

    /// [`Self::search`] against explicit translations: a preset matches on
    /// its English name, its translated name, or any translated search term,
    /// so typing either language finds it.
    pub fn search_in(
        &self,
        translations: Option<&PresetTranslations>,
        query: &str,
        geometry: Geometry,
        limit: usize,
    ) -> Vec<&Preset> {
        self.search_geometries_in(translations, query, &[geometry], limit)
    }

    /// [`Self::search_in`] across several geometries, best first: every
    /// matching preset of `geometries[0]`, then those of `geometries[1]`
    /// not already listed, and so on. This is how a closed way is offered
    /// both area and line presets.
    pub fn search_geometries_in(
        &self,
        translations: Option<&PresetTranslations>,
        query: &str,
        geometries: &[Geometry],
        limit: usize,
    ) -> Vec<&Preset> {
        let q = query.to_lowercase();
        let mut out: Vec<&Preset> = Vec::new();
        for geometry in geometries {
            let mut found = self
                .presets
                .iter()
                .filter(|p| p.geometry.contains(geometry))
                .filter(|p| !out.iter().any(|seen| seen.id == p.id))
                .filter(|p| {
                    q.is_empty()
                        || p.name.to_lowercase().contains(&q)
                        || translations.is_some_and(|t| t.preset_matches(&p.id, &q))
                })
                .collect::<Vec<_>>();
            // Within a geometry, an exact name match ("Building") ranks
            // above longer names that merely contain the query (stable).
            if !q.is_empty() {
                found.sort_by_key(|p| {
                    p.name.to_lowercase() != q && p.display_name(translations).to_lowercase() != q
                });
            }
            out.extend(found);
        }
        out.truncate(limit);
        out
    }
}

/// Look up a friendly `(name, icon)` pair for a feature. Always returns a
/// name: falls back to the geometry's generic name (e.g. "Point") if
/// nothing in `index` matches at all, which should only happen if `index`
/// is missing the vendored schema's own geometry-only fallback presets
/// (e.g. in a minimal test fixture).
pub fn describe_feature(
    index: &PresetIndex,
    tags: &HashMap<String, String>,
    geometry: Geometry,
) -> (String, Option<String>) {
    describe_feature_in(active(), index, tags, geometry)
}

/// [`describe_feature`] with the name taken from explicit translations (the
/// English schema name where they have none).
pub fn describe_feature_in(
    translations: Option<&PresetTranslations>,
    index: &PresetIndex,
    tags: &HashMap<String, String>,
    geometry: Geometry,
) -> (String, Option<String>) {
    match index.match_feature(tags, geometry) {
        Some(preset) => (
            preset.display_name(translations).to_string(),
            preset.icon.clone(),
        ),
        None => (geometry.fallback_name().to_string(), None),
    }
}

/// The icon-set prefixes a preset's `icon` name can carry, each vendored
/// flat into `assets/presets/icons/<name>.svg` by
/// `examples/update_presets.rs`: Maki, Temaki, iD's own preset icons,
/// Röntgen and Font Awesome (solid, regular, brands).
pub const ICON_PREFIXES: &[&str] = &[
    "maki-",
    "temaki-",
    "iD-",
    "roentgen-",
    "fas-",
    "far-",
    "fab-",
];

/// The embedded SVG source for an icon name (e.g. `"maki-cafe"`), by binary
/// search of [`PRESET_ICONS`]. `None` for an unknown name.
pub fn icon_svg(icon_name: &str) -> Option<&'static str> {
    PRESET_ICONS
        .binary_search_by(|(name, _)| (*name).cmp(icon_name))
        .ok()
        .map(|i| PRESET_ICONS[i].1)
}

/// Resolve a preset's `icon` field (e.g. `"maki-cafe"`, `"temaki-bench"`,
/// `"iD-highway-residential"`) to the asset path GPUI loads it from
/// (`preset-icons/<name>.svg`, served from memory by `AppAssets`), if the
/// icon is embedded. Returns `None` for names with an unknown set prefix and
/// for icons that could not be vendored, so callers render no icon (see
/// [`icon_path_or_fallback`]) rather than pointing GPUI at a missing asset.
pub fn icon_path(icon_name: &str) -> Option<gpui::SharedString> {
    if !ICON_PREFIXES.iter().any(|p| icon_name.starts_with(p)) {
        return None;
    }
    icon_svg(icon_name)?;
    Some(format!("{ICON_ASSET_DIR}{icon_name}.svg").into())
}

/// Whether the icon behind this asset path is a multi-colour illustration
/// (every iD icon: road and water pictograms with several fills, grey
/// shading and `currentColor` parts). GPUI's `svg()` paints an SVG as a
/// single-colour alpha mask, which turns those into solid blobs, so they are
/// drawn through `img()` instead, which rasterises the SVG in full colour.
pub fn is_colour_icon(asset_path: &str) -> bool {
    asset_path
        .strip_prefix(ICON_ASSET_DIR)
        .is_some_and(|name| name.starts_with("iD-"))
}

/// A square preset icon of `size` pixels for an asset path from
/// [`icon_path`]. Single-colour icons are masks tinted with `color`;
/// multi-colour ones ([`is_colour_icon`]) keep their own colours.
pub fn icon_element(
    path: gpui::SharedString,
    size: f32,
    color: gpui::Hsla,
) -> gpui::AnyElement {
    use gpui::{IntoElement, ObjectFit, Styled, StyledImage};
    if is_colour_icon(&path) {
        gpui::img(path)
            .size(gpui::px(size))
            .object_fit(ObjectFit::Contain)
            .into_any_element()
    } else {
        gpui::svg()
            .path(path)
            .size(gpui::px(size))
            .text_color(color)
            .into_any_element()
    }
}

/// The embedded SVG bytes behind an asset path produced by [`icon_path`].
pub fn icon_asset(asset_path: &str) -> Option<&'static [u8]> {
    let name = asset_path
        .strip_prefix(ICON_ASSET_DIR)?
        .strip_suffix(".svg")?;
    icon_svg(name).map(str::as_bytes)
}

/// The generic icon shown for a feature of this geometry when its preset has
/// no icon (or its icon is not embedded). Mirrors iD, which falls back to a
/// point / vertex / line / area / relation glyph. The line glyph is Font
/// Awesome's bezier curve (a drawn line with its handles): iD's own
/// `iD-other-line` is a small road-perspective tile that reads as a blob at
/// 24px, and no Maki/Temaki/Röntgen icon is a neutral line.
pub fn fallback_icon_name(geometry: Geometry) -> &'static str {
    match geometry {
        Geometry::Point => "maki-marker-stroked",
        Geometry::Vertex => "maki-circle-stroked",
        Geometry::Line => "fas-bezier-curve",
        Geometry::Area => "maki-square-stroked",
        Geometry::Relation => "iD-relation",
    }
}

/// Every geometry's fallback icon name, so the fetch tool vendors them even
/// if no preset happens to reference them.
pub const FALLBACK_ICON_NAMES: &[&str] = &[
    "maki-marker-stroked",
    "maki-circle-stroked",
    "fas-bezier-curve",
    "maki-square-stroked",
    "iD-relation",
];

/// The icon asset to draw for a feature: its preset icon when that resolves,
/// else the geometry's generic fallback. `None` only if even the fallback
/// is not embedded.
pub fn icon_path_or_fallback(
    icon_name: Option<&str>,
    geometry: Geometry,
) -> Option<gpui::SharedString> {
    icon_name
        .and_then(icon_path)
        .or_else(|| icon_path(fallback_icon_name(geometry)))
}

/// Vendored copy of iD's `areaKeys.json`: which tag keys imply an area for
/// a *closed* way, and which specific values of those keys are excluded
/// (i.e. still imply a line even when the way is closed). A key mapped to
/// an empty inner map means every value of that key implies area.
pub struct AreaKeys(HashMap<String, HashMap<String, bool>>);

impl AreaKeys {
    pub fn from_json(body: &str) -> Result<Self, serde_json::Error> {
        let map: HashMap<String, HashMap<String, bool>> = serde_json::from_str(body)?;
        Ok(Self(map))
    }

    /// Whether a closed way with these tags should be treated as an area
    /// rather than a line (iD's `isArea` for a closed way): `area=yes`
    /// always makes it one, `area=no` never does, otherwise any tag whose
    /// key is an area key and whose value isn't excluded does. Says nothing
    /// about open ways, which are never areas. An untagged closed way is
    /// *not* an area by tags alone; see [`way_geometry`].
    pub fn closed_way_is_area(&self, tags: &HashMap<String, String>) -> bool {
        match tags.get("area").map(String::as_str) {
            Some("yes") => return true,
            Some("no") => return false,
            _ => {}
        }
        for (key, value) in tags {
            if let Some(excluded_values) = self.0.get(key) {
                if !excluded_values.contains_key(value) {
                    return true;
                }
            }
        }
        false
    }
}

/// The geometry a way is treated as for preset matching. An open way is a
/// `Line`. A closed way is an `Area` when its tags say so (see
/// [`AreaKeys::closed_way_is_area`]), a `Line` when they say otherwise, and
/// an `Area` when it has no tags at all: that is a freshly drawn closed
/// shape, and the generic Area preset (with the area presets reachable from
/// the picker) is the least surprising reading of it.
pub fn way_geometry(
    tags: &HashMap<String, String>,
    closed: bool,
    area_keys: &AreaKeys,
) -> Geometry {
    if !closed {
        Geometry::Line
    } else if tags.is_empty() || area_keys.closed_way_is_area(tags) {
        Geometry::Area
    } else {
        Geometry::Line
    }
}

/// Geometries whose presets the picker offers for a way, best first. An
/// open way is only ever a line. A closed way can be either (a roundabout or
/// a fence loop is a closed line), so both are offered, ordered by
/// [`way_geometry`]: an area (or untagged) closed way lists area presets
/// first, a line-tagged closed way lists line presets first.
pub fn way_candidate_geometries(
    tags: &HashMap<String, String>,
    closed: bool,
    area_keys: &AreaKeys,
) -> Vec<Geometry> {
    if !closed {
        return vec![Geometry::Line];
    }
    match way_geometry(tags, closed, area_keys) {
        Geometry::Area => vec![Geometry::Area, Geometry::Line],
        _ => vec![Geometry::Line, Geometry::Area],
    }
}

/// The tag edits that applying a preset makes to a feature, as
/// `(key, new value or None to remove)` sorted by key, omitting no-ops.
/// Preset tags overwrite; a `*` value (any value of that key) keeps the
/// feature's existing value or else becomes `yes`, as in iD. Existing tags
/// the preset doesn't mention stay. For a closed way (`closed`), an
/// area-only preset whose tags wouldn't by themselves make it an area also
/// sets `area=yes`, and a line-only preset removes an existing `area=yes`.
pub fn preset_tag_changes(
    preset_tags: &HashMap<String, String>,
    preset_geometry: &[Geometry],
    existing: &HashMap<String, String>,
    closed: bool,
    area_keys: &AreaKeys,
) -> Vec<(String, Option<String>)> {
    let mut merged = existing.clone();
    for (key, value) in preset_tags {
        if value == "*" {
            merged.entry(key.clone()).or_insert_with(|| "yes".into());
        } else {
            merged.insert(key.clone(), value.clone());
        }
    }
    if closed {
        let area_only =
            preset_geometry.contains(&Geometry::Area) && !preset_geometry.contains(&Geometry::Line);
        let line_only =
            preset_geometry.contains(&Geometry::Line) && !preset_geometry.contains(&Geometry::Area);
        if area_only && !area_keys.closed_way_is_area(&merged) {
            merged.insert("area".into(), "yes".into());
        } else if line_only && merged.get("area").map(String::as_str) == Some("yes") {
            merged.remove("area");
        }
    }
    let mut changes: Vec<(String, Option<String>)> = Vec::new();
    for (key, after) in &merged {
        if existing.get(key) != Some(after) {
            changes.push((key.clone(), Some(after.clone())));
        }
    }
    for key in existing.keys() {
        if !merged.contains_key(key) {
            changes.push((key.clone(), None));
        }
    }
    changes.sort();
    changes
}

/// Classify a feature's geometry for preset matching: a node not referenced
/// by any way is a `Point`; a node referenced by at least one way is a
/// `Vertex`; a way is classified by [`way_geometry`]; a relation is always
/// `Relation`. Returns `None` if the feature id isn't present in `data`.
pub fn classify_geometry(
    data: &OsmData,
    kind: FeatureKind,
    id: i64,
    area_keys: &AreaKeys,
) -> Option<Geometry> {
    match kind {
        FeatureKind::Node => {
            data.nodes.get(&id)?;
            let referenced = data.ways.values().any(|way| way.nodes.contains(&id));
            Some(if referenced {
                Geometry::Vertex
            } else {
                Geometry::Point
            })
        }
        FeatureKind::Way => {
            let way = data.ways.get(&id)?;
            Some(way_geometry(&way.tags, way.is_closed(), area_keys))
        }
        FeatureKind::Relation => data
            .relations
            .iter()
            .any(|r| r.id == id)
            .then_some(Geometry::Relation),
    }
}

#[cfg(test)]
